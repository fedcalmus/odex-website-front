// Builds the icon system from src/icons/source/*.svg (one 24px master SVG
// per icon, exported from Figma — sizes above 16 all scale losslessly since
// they're the same vector artwork, so we only keep one file per icon).
//
// Emits:
//   public/icons/sprite.svg                       — one <symbol> per icon, single <use>-able asset
//   src/components/Icon/icon-names.generated.ts    — typed union of valid icon names
//
// Run via `npm run icons:build` (also wired into predev/prebuild).
import { readdir, readFile, writeFile, mkdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = path.dirname(fileURLToPath(import.meta.url)) + "/..";
const sourceDir = path.join(rootDir, "src/icons/source");
const spriteOutPath = path.join(rootDir, "public/icons/sprite.svg");
const typesOutPath = path.join(
  rootDir,
  "src/components/Icon/icon-names.generated.ts",
);

// The exported icon set is single-colour (#F2F5F2 = text/primary) — swap it
// for currentColor so consumers drive colour via the `color` prop/CSS.
const HARDCODED_COLOR = /#F2F5F2/gi;

function toIconId(name) {
  return `icon-${name}`;
}

async function main() {
  const files = (await readdir(sourceDir)).filter((f) => f.endsWith(".svg"));
  if (files.length === 0) {
    throw new Error(`No SVGs found in ${sourceDir}`);
  }

  const names = [];
  const symbols = [];

  for (const file of files.sort()) {
    const name = path.basename(file, ".svg");
    const raw = await readFile(path.join(sourceDir, file), "utf8");

    const viewBoxMatch = raw.match(/viewBox="([^"]+)"/);
    if (!viewBoxMatch) {
      throw new Error(`${file}: missing viewBox`);
    }
    const viewBox = viewBoxMatch[1];

    const innerMatch = raw.match(/<svg[^>]*>([\s\S]*)<\/svg>/);
    if (!innerMatch) {
      throw new Error(`${file}: could not parse <svg> contents`);
    }
    const inner = innerMatch[1].trim().replace(HARDCODED_COLOR, "currentColor");

    // Carry the root <svg fill> onto the <symbol>. The exports are stroke-only
    // (`fill="none"` on the root); dropping it makes every open path fall back
    // to the default black fill, which shows as a dark sliver inside a check
    // or an arrowhead.
    const rootFill = raw.match(/<svg[^>]*\sfill="([^"]+)"/)?.[1];
    const fillAttr = rootFill ? ` fill="${rootFill}"` : "";

    names.push(name);
    symbols.push(
      `<symbol id="${toIconId(name)}" viewBox="${viewBox}"${fillAttr}>${inner}</symbol>`,
    );
  }

  const sprite = `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">\n${symbols.join("\n")}\n</svg>\n`;

  await mkdir(path.dirname(spriteOutPath), { recursive: true });
  await writeFile(spriteOutPath, sprite, "utf8");

  const typesFile = `// Generated by scripts/build-icons.mjs — do not edit by hand.
// Run \`npm run icons:build\` after adding/removing files in src/icons/source.

export const ICON_NAMES = [
${names.map((n) => `  "${n}",`).join("\n")}
] as const;

export type IconName = (typeof ICON_NAMES)[number];
`;

  await mkdir(path.dirname(typesOutPath), { recursive: true });
  await writeFile(typesOutPath, typesFile, "utf8");

  console.log(`Built sprite with ${names.length} icons -> ${path.relative(rootDir, spriteOutPath)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
